"""Generate commands.h for the hisense_w4a1 ESPHome component from pyaehw4a1.

The frames are pyaehw4a1.commands' update frames, the same ones the Home Assistant
integration sends, so the two can't drift apart. A few frames pyaehw4a1 doesn't
have are made from its frames by changing single bytes; each change was tested
on the AC first (docs/frames.md).

Frames are written without their checksum, end marker or F4 escaping, so the
byte numbers match the docs and the component can change a byte before sending.
The component adds the rest when it sends a frame (frame.h).

Usage, from the repository root:
    pip install pyaehw4a1==0.3.9
    python3 tools/gen_hisense_commands.py > components/hisense_w4a1/commands.h

If pyaehw4a1 is installed somewhere else, pass that site-packages folder as
the first argument.
"""

import importlib.metadata
import sys

if len(sys.argv) > 1:
    sys.path.insert(0, sys.argv[1])

from pyaehw4a1.commands import ReadCommand, UpdateCommand  # noqa: E402

# Celsius only: the AC reports temperature_Fahrenheit = 0. pyaehw4a1's turbo,
# energysave and sleep frames are left out: they carry other settings too, and
# the AC ignored or undid them.
NAMES = [
    "on",
    "off",
    "mode_heat",
    "mode_cool",
    "mode_dry",
    "mode_fan",
    "speed_auto",
    "speed_mute",
    "speed_low",
    "speed_med",
    "speed_max",
    "display_on",
    "display_off",
    "vert_dir",
    "vert_swing",
    "hor_dir",
    "hor_swing",
]
TEMPS = range(16, 33)

# name: (pyaehw4a1 frame or an earlier entry here, {byte number: new value})
DERIVED = {
    # Changes nothing: display_on without its display setting. The component
    # builds the preset frames from it.
    "noop": ("display_on", {36: 0x00}),
    # The AC's second and fourth fan speeds, which pyaehw4a1's speeds skip.
    "speed_2": ("speed_low", {16: 0x0D}),
    "speed_4": ("speed_max", {16: 0x11}),
    # SMART on the remote: the AC picks the mode and setpoint itself.
    "smart": ("noop", {18: 0xB0}),
}

FRAME_LEN = 46  # update frames from F4 F5 up to the checksum


def unescaped_body(name: str) -> bytearray:
    """A pyaehw4a1 frame as the docs number it, without checksum and end marker."""
    raw = UpdateCommand[name].value
    assert raw[:2] == b"\xf4\xf5" and raw[-2:] == b"\xf4\xfb", name
    frame = raw[:2] + raw[2:-2].replace(b"\xf4\xf4", b"\xf4") + raw[-2:]
    body, checksum = frame[:-4], int.from_bytes(frame[-4:-2], "big")
    assert len(frame) == body[4] + 9, name
    assert sum(body[2:]) & 0xFFFF == checksum, name
    assert len(body) == FRAME_LEN, name
    return bytearray(body)


def c_bytes(data: bytes) -> str:
    return ", ".join(f"0x{b:02X}" for b in data)


frames = {name: unescaped_body(name) for name in NAMES}
for t in TEMPS:
    frames[f"temp_{t}_C"] = unescaped_body(f"temp_{t}_C")
for name, (base, changes) in DERIVED.items():
    body = bytearray(frames[base])
    for index, value in changes.items():
        body[index] = value
    frames[name] = body

# The do-nothing frame must be exactly the one tested: header, byte 23 = 0x04
# (set by every pyaehw4a1 command) and nothing else.
expected_noop = bytearray.fromhex("F4F5004029000001 01FE010000650000") + bytes(30)
expected_noop[23] = 0x04
assert frames["noop"] == expected_noop

version = importlib.metadata.version("pyaehw4a1")
out = [
    f"// Generated by esphome/tools/gen_hisense_commands.py from pyaehw4a1 {version}.",
    "// Don't edit by hand; rerun the script instead.",
    "#pragma once",
    "",
    "#include <cstddef>",
    "#include <cstdint>",
    "",
    "namespace esphome {",
    "namespace hisense_w4a1 {",
    "",
    "// An update frame from F4 F5 up to the checksum, without the checksum, the",
    "// F4 FB end marker or F4 escaping. frame.h adds those when it's sent.",
    "struct Command {",
    "  const char *name;",
    "  const uint8_t *data;",
    "  size_t len;",
    "};",
    f"static const size_t CMD_LEN = {FRAME_LEN};",
    "",
    "// ReadCommand.status_102_0, ready to send: asks for the full status frame (type 102/0).",
    f"static const uint8_t STATUS_REQUEST[] = {{{c_bytes(ReadCommand.status_102_0.value)}}};",
    "",
]
names = NAMES + list(DERIVED)
for name in names:
    out.append(f"static const uint8_t CMD_{name.upper()}_DATA[] = {{{c_bytes(frames[name])}}};")
for t in TEMPS:
    out.append(f"static const uint8_t CMD_TEMP_{t}_C_DATA[] = {{{c_bytes(frames[f'temp_{t}_C'])}}};")
out.append("")
for name in names:
    out.append(f'static const Command CMD_{name.upper()}{{"{name}", CMD_{name.upper()}_DATA, CMD_LEN}};')
out.append("")
out.append(f"static const uint8_t MIN_TEMP_C = {TEMPS.start};")
out.append(f"static const uint8_t MAX_TEMP_C = {TEMPS.stop - 1};")
out.append("// Indexed by temperature - MIN_TEMP_C.")
out.append("static const Command CMD_TEMP_C[] = {")
for t in TEMPS:
    out.append(f'    {{"temp_{t}_C", CMD_TEMP_{t}_C_DATA, CMD_LEN}},')
out.append("};")
out += ["", "}  // namespace hisense_w4a1", "}  // namespace esphome", ""]
print("\n".join(out))
